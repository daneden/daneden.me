/**
 * Terrazzo plugin: writes tokens.css from the resolver in site.resolver.json.
 *
 * - Default theme tokens go on :root.
 * - Values that differ between the light and dark schemes become
 *   light-dark(<light>, <dark>), so an element (or a whole page) can lock its
 *   scheme with `color-scheme: light|dark` and every token follows.
 * - Each non-default theme becomes a [data-theme="<name>"] block containing
 *   only the tokens that differ from the default theme.
 *
 * Relies on @terrazzo/plugin-css having transformed every scheme × theme
 * permutation (see terrazzo.config.mjs).
 */
export default function lightDark({ filename = "tokens.css", schemes = ["light", "dark"], themes = ["default"] } = {}) {
  const [light, dark] = schemes

  return {
    name: "light-dark",
    build({ getTransforms, outputFile }) {
      const valueOf = (t) => (typeof t.value === "string" ? t.value : t.value["."])

      function declarations(theme) {
        const values = new Map()
        for (const scheme of [light, dark]) {
          for (const t of getTransforms({ format: "css", input: { scheme, theme } })) {
            const entry = values.get(t.localID) ?? { id: t.id }
            entry[scheme] = valueOf(t)
            values.set(t.localID, entry)
          }
        }
        const out = new Map()
        for (const [name, v] of values) {
          out.set(name, v[light] === v[dark] ? v[light] : `light-dark(${v[light]}, ${v[dark]})`)
        }
        return out
      }

      const base = declarations("default")
      const block = (selector, decls) =>
        `${selector} {\n${[...decls].map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`

      let css = `/* Generated by Terrazzo from tokens/site.resolver.json. Do not edit; run \`bun run tokens\`. */\n\n`
      css += block(":root", base)

      for (const theme of themes.filter((t) => t !== "default")) {
        const diff = [...declarations(theme)].filter(([k, v]) => base.get(k) !== v)
        css += `\n` + block(`[data-theme="${theme}"]`, diff)
      }

      outputFile(filename, css)
    },
  }
}
